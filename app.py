@app.route('/calculate', methods=['POST'])
def calculate_route():
    # Parse form data
    cities = request.form.getlist('cities')
    start_city_name = request.form.get('start_city', '')
    connection_starts = request.form.getlist('connection_start')
    connection_stops = request.form.getlist('connection_stop')

    start_day_raw = request.form.get('start_day', '').strip()
    start_day = int(start_day_raw) if start_day_raw else None

    high_temp = float(request.form.get('high_temp', 25))
    low_temp  = float(request.form.get('low_temp', 15))

    high_temp_min = request.form.get('high_temp_min', '').strip()
    high_temp_min = float(high_temp_min) if high_temp_min else float('-inf')

    high_temp_max = request.form.get('high_temp_max', '').strip()
    high_temp_max = float(high_temp_max) if high_temp_max else float('inf')

    low_temp_min = request.form.get('low_temp_min', '').strip()
    low_temp_min = float(low_temp_min) if low_temp_min else float('-inf')

    low_temp_max = request.form.get('low_temp_max', '').strip()
    low_temp_max = float(low_temp_max) if low_temp_max else float('inf')

    daily_km  = float(request.form.get('daily_km', 100))
    max_days  = int(request.form.get('max_days', 30))
    elev_points_per_1000km = int(request.form.get('elev_points_per_1000km', 1000))
    temp_weight = float(request.form.get('temp_weight', 0.5))
    warming_factor = float(request.form.get('warming_factor', 0.6))

    routing_mode = request.form.get('routing_mode', 'car')
    if routing_mode not in ('car', 'bicycle', 'car_no_highway'):
        routing_mode = 'car'

    sorted_input = request.form.get('sorted_input') == 'true'

    blocked_countries = request.form.getlist('blocked_countries')
    additional_blocked = request.form.getlist('additional_blocked_countries')
    country_map = {c.name: c.alpha_2 for c in pycountry.countries}
    for name in additional_blocked:
        code = country_map.get(name)
        if code:
            blocked_countries.append(code)

    city_rest_days_raw = request.form.getlist('city_rest_days')

    # Resolve each city name with fuzzy/umlaut-tolerant matching
    resolved_cities = []   # [(original_stripped, city_id, matched_key)]
    for city in cities:
        city_id, matched_key = resolve_city_name(city)
        resolved_cities.append((city.strip(), city_id, matched_key))

    city_ids = []
    city_rest_days = {}
    for i, (orig, city_id, matched_key) in enumerate(resolved_cities):
        if city_id is not None:
            city_ids.append(city_id)
            try:
                rest = int(city_rest_days_raw[i]) if i < len(city_rest_days_raw) else 0
            except (ValueError, TypeError):
                rest = 0
            if rest > 0:
                city_rest_days[city_id] = rest

    connections = []
    for start, stop in zip(connection_starts, connection_stops):
        s_id, s_key = resolve_city_name(start)
        e_id, e_key = resolve_city_name(stop)
        if s_id is not None and e_id is not None:
            connections.append((s_id, e_id))

    start_city, start_matched_key = resolve_city_name(start_city_name)

    print("Connections:", connections)
    print("start city:", start_city)
    print("cities:", city_ids)
    print("sorted_input:", sorted_input)
    print(blocked_countries)

    # ── Server-side validation ───────────────────────────────────────────
    unrecognized = [orig for orig, city_id, _ in resolved_cities
                    if city_id is None and orig]
    corrections  = [(orig, matched_key) for orig, city_id, matched_key in resolved_cities
                    if city_id is not None and orig.lower() != matched_key]
    validation_errors = []
    warnings = []

    if not city_ids and not start_city:
        if unrecognized:
            validation_errors.append(
                f'Keine Städte erkannt. Nicht gefundene Städte: {", ".join(unrecognized)}. '
                f'Bitte Schreibweise prüfen (Autocomplete verwenden).'
            )
        else:
            validation_errors.append('Bitte mindestens eine Stadt eingeben.')

    if unrecognized and city_ids:
        validation_errors.append(
            f'Folgende Städte wurden nicht gefunden und werden übersprungen: '
            f'{", ".join(unrecognized)}.'
        )

    if corrections:
        warnings.append(
            'Eingaben automatisch korrigiert: '
            + ', '.join(f'„{orig}" → „{key}"' for orig, key in corrections)
        )

    if start_city_name and not start_city:
        validation_errors.append(
            f'Startstadt „{start_city_name}" nicht gefunden. Bitte Schreibweise prüfen.'
        )
    elif start_city_name and start_matched_key and start_city_name.strip().lower() != start_matched_key:
        warnings.append(f'Startstadt „{start_city_name.strip()}" als „{start_matched_key}" erkannt.')

    if low_temp > high_temp:
        validation_errors.append(
            f'Nachttemperatur ({low_temp:.1f}°C) darf nicht höher sein als '
            f'Tagestemperatur ({high_temp:.1f}°C).'
        )

    if (high_temp_min != float('-inf') and high_temp_max != float('inf')
            and high_temp_min > high_temp_max):
        validation_errors.append(
            f'Tagestemperatur Bereich: Min ({high_temp_min:.1f}°C) ist größer als '
            f'Max ({high_temp_max:.1f}°C).'
        )

    if (low_temp_min != float('-inf') and low_temp_max != float('inf')
            and low_temp_min > low_temp_max):
        validation_errors.append(
            f'Nachttemperatur Bereich: Min ({low_temp_min:.1f}°C) ist größer als '
            f'Max ({low_temp_max:.1f}°C).'
        )

    if daily_km < 1:
        validation_errors.append('Max. Tagesstrecke muss mindestens 1 km betragen.')

    if max_days < 1:
        validation_errors.append('Max. Reisetage muss mindestens 1 betragen.')

    # Connections: flag pairs where only one side was recognized
    for start, stop in zip(connection_starts, connection_stops):
        if start.strip() and stop.strip():
            s_id, _ = resolve_city_name(start)
            e_id, _ = resolve_city_name(stop)
            if s_id is None and e_id is None:
                validation_errors.append(
                    f'Verbindung „{start} → {stop}": Beide Städte nicht gefunden.'
                )
            elif s_id is None:
                validation_errors.append(
                    f'Verbindung: Startstadt „{start}" nicht gefunden.'
                )
            elif e_id is None:
                validation_errors.append(
                    f'Verbindung: Zielstadt „{stop}" nicht gefunden.'
                )

    # "übersprungen" messages are non-blocking warnings, everything else blocks
    blocking = [e for e in validation_errors if 'übersprungen' not in e]
    skip_warnings = [e for e in validation_errors if 'übersprungen' in e]
    all_warnings = skip_warnings + warnings
    if blocking:
        return render_template('error.html',
                               errors=blocking,
                               warnings=all_warnings)

    params = dict(
        city_ids=city_ids,
        start_city=start_city,
        connections=connections,
        start_day=start_day,
        low_temp=low_temp,
        high_temp=high_temp,
        high_temp_min=high_temp_min,
        high_temp_max=high_temp_max,
        low_temp_min=low_temp_min,
        low_temp_max=low_temp_max,
        daily_km=daily_km,
        max_days=max_days,
        elev_points_per_1000km=elev_points_per_1000km,
        temp_weight=temp_weight,
        warming_factor=warming_factor,
        routing_mode=routing_mode,
        sorted_input=sorted_input,
        blocked_countries=blocked_countries,
        city_rest_days=city_rest_days,
    )

    job_id = str(uuid.uuid4())
    jobs[job_id] = {
        'status':     'starting',
        'step':       1,
        'message':    'Starte Berechnung...',
        'osrm_done':  0,
        'osrm_total': 0,
        'rough_map':  None,
        'result':     None,
        'error':      None,
    }

    t = threading.Thread(target=run_calculation, args=(job_id, params), daemon=True)
    t.start()

    return render_template('loading.html', job_id=job_id)


@app.route('/status/<job_id>')
def job_status(job_id):
    job = jobs.get(job_id)
    if not job:
        return jsonify({'status': 'error', 'error': 'Job nicht gefunden'})
    return jsonify({
        'status':     job['status'],
        'step':       job['step'],
        'message':    job['message'],
        'osrm_done':  job['osrm_done'],
        'osrm_total': job['osrm_total'],
        'rough_map':  job['rough_map'],
        'error':      job.get('error'),
    })


@app.route('/result/<job_id>')
def job_result(job_id):
    job = jobs.get(job_id)
    if not job or job['status'] != 'done' or not job.get('result'):
        return render_template('error.html', message="Ergebnis nicht verfügbar")
    r = job['result']
    return render_template('results.html',
                           map_html=r['map_html'],
                           elevation_svg=r['elevation_svg'],
                           route_weather_json=r['route_weather_json'],
                           route=r['route'],
                           start_day=r['start_day'],
                           overall_distance=r['overall_distance'],
                           desired_low_temp=r['desired_low_temp'],
                           desired_high_temp=r['desired_high_temp'],
                           city_rest_days=r['city_rest_days'])


if __name__ == '__main__':
    app.run(debug=True)
