def run_calculation(job_id, params):
    job = jobs[job_id]

    def update(step, message, **kwargs):
        job['step'] = step
        job['message'] = message
        for k, v in kwargs.items():
            job[k] = v

    try:
        update(1, "Routenalgorithmus läuft...")

        city_ids_by_country = load_city_ids_by_country('data/city_ids_by_country.json')

        # ── Fast feasibility pre-check (uses a graph copy, does not mutate global) ──
        feasibility_issues = check_route_feasibility(
            city_graph,
            target_cities=params['city_ids'],
            start_city=params['start_city'],
            connections=params['connections'],
            blocked_countries=params['blocked_countries'],
            city_ids_by_country=city_ids_by_country,
        )
        if feasibility_issues:
            issue_text = ' | '.join(feasibility_issues)
            job['status'] = 'error'
            job['error'] = issue_text
            job['message'] = 'Städte nicht erreichbar'
            return

        route, start_day, fail_reason = find_optimal_route(
            city_graph,
            params['blocked_countries'],
            city_ids_by_country,
            temperatures,
            target_cities=params['city_ids'],
            start_city=params['start_city'],
            connections=params['connections'],
            start_day=params['start_day'],
            desired_low_temp=params['low_temp'],
            desired_high_temp=params['high_temp'],
            temp_weight=params['temp_weight'],
            auto_threshold_percentile=10,
            exp=2,
            low_temp_range=(params['low_temp_min'], params['low_temp_max']),
            high_temp_range=(params['high_temp_min'], params['high_temp_max']),
            daily_max_km=params['daily_km'],
            max_days=params['max_days'],
            sorted_input=params['sorted_input'],
            city_rest_days=params['city_rest_days'],
            warming_factor=params['warming_factor'],
        )

        if not route:
            job['status'] = 'error'
            job['error'] = fail_reason or 'Kein gültiger Routenverlauf gefunden.'
            job['message'] = 'Keine Route gefunden'
            return

        # Build rough map data (straight lines, no OSRM) and show immediately
        rough_map = create_loading_route_map(
            city_graph, temperatures, route, 2,
            params['low_temp'], params['high_temp'],
            params['low_temp_min'], params['low_temp_max'],
            params['high_temp_min'], params['high_temp_max'],
            warming_factor=params['warming_factor'],
        )
        update(2, "Route gefunden! Straßenverlauf wird geladen...",
               status='route_found', rough_map=rough_map,
               osrm_done=0, osrm_total=max(0, len(route) - 1))

        # OSRM progress counter (cumulative across all sub-routes)
        osrm_counter = [0]
        total_est = max(1, len(route) - 1)

        def osrm_progress(done_in_sub, total_in_sub):
            osrm_counter[0] += 1
            job['osrm_done'] = osrm_counter[0]
            job['osrm_total'] = max(osrm_counter[0], total_est)
            job['message'] = (f"Straßen: {osrm_counter[0]}/"
                              f"{job['osrm_total']} Segmente geladen")

        route_map, elevation_svg, osrm_distances = create_route_map(
            city_graph, temperatures, route, 2,
            params['low_temp'], params['high_temp'],
            params['low_temp_min'], params['low_temp_max'],
            params['high_temp_min'], params['high_temp_max'],
            connections=params['connections'],
            show_elevation=True,
            routing_mode=params['routing_mode'],
            elev_points_per_1000km=params['elev_points_per_1000km'],
            progress_callback=osrm_progress,
            warming_factor=params['warming_factor'],
        )

        update(3, "Höhenprofil wird erstellt...", status='running')

        overall_distance = sum(d for d in osrm_distances if d > 0)
        route_with_osrm = [
            (city_id, day, city_name, osrm_distances[i] if i < len(osrm_distances) else 0)
            for i, (city_id, day, city_name, _) in enumerate(route)
        ]
        route_weather_json = build_route_weather_json(
            city_graph, temperatures, route, start_day,
            warming_factor=params['warming_factor'],
        )

        job['result'] = {
            'map_html':          route_map._repr_html_(),
            'elevation_svg':     elevation_svg,
            'route_weather_json': route_weather_json,
            'route':             route_with_osrm,
            'start_day':         start_day,
            'overall_distance':  overall_distance,
            'desired_low_temp':  params['low_temp'],
            'desired_high_temp': params['high_temp'],
            'city_rest_days':    params['city_rest_days'],
        }
        update(3, "Fertig!", status='done')

    except Exception as e:
        import traceback
        traceback.print_exc()
        job['status'] = 'error'
        job['error'] = str(e)
        job['message'] = f"Fehler: {e}"


